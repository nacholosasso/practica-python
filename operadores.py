#Operadores aritméticos
#suma o adicion
numero_uno = 5
numero_dos = 4
resultado = numero_uno + numero_dos
resultado = str(resultado)
print("suma: " + resultado)
#resta o substraccion
numero_uno = 5
numero_dos = 4
resultado = numero_uno - numero_dos
resultado = str(resultado)
#multiplicacion
print("resta: " + resultado)
#multiplicacion
numero_uno = 5
numero_dos = 4
resultado = numero_uno * numero_dos
print("multiplicacion: " + str(resultado))
#exponencia o potencia
numero_uno = 2
exponente = 5
resultado = numero_uno ** exponente
print("exponenciacion: " + str(resultado))
#division
numero_uno = 4
numero_dos = 2
resultado = numero_uno / numero_dos
print("division: " + str(resultado))
#modulo o resto ( lo que le flata a ldivision para ser un numero entero)
numero_uno = 30
numero_dos = 8
resultado = numero_uno % numero_dos
print("modulo: " + str(resultado))
#division entera o floor division (redondea hacia abajo el resultado de la division)
numero_uno = 10
numero_dos = 3
resultado = numero_uno // numero_dos
print("division entera: " + str(resultado))
